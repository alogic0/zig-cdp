const std = @import("std");
const H = @import("cli_support.zig");
pub fn run(c: H.Context) !void {
    var server = try H.Session.start(c, "agent", &.{});
    defer server.deinit();
    try exercise(.{ .c = c, .target = server.path }, null);
    try server.close();
}
pub fn exercise(client: H.Client, download_url: ?[]const u8) !void {
    const c = client.c;
    _ = try client.result(&.{ "content", @embedFile("fixtures/agent.html") });
    if (download_url) |url| _ = try client.result(&.{ "eval", try c.a.print("window.fixtureDownloadUrl={s}", .{try c.json(url)}) });
    const nodes = try H.arr(try client.result(&.{"snapshot"}), "nodes");
    var slider = false;
    var textbox = false;
    for (nodes) |node| {
        if (H.is(try H.field(node, "role"), "slider") and H.is(try H.field(node, "name"), "Volume")) slider = true;
        if (H.is(try H.field(node, "role"), "textbox") and H.is(try H.field(node, "name"), "Name")) textbox = true;
    }
    try H.check(slider and textbox, "real accessibility roles and names");
    const clipped = try client.result(&.{ "snapshot", "--limit", "40" });
    try H.check((try H.field(clipped, "truncated")).bool and (try H.field(clipped, "returned_bytes")).integer <= 40, "bounded snapshot");
    _ = try client.result(&.{ "fill", "--role", "textbox", "--name", "Name", "--value", "Sample 🧭" });
    _ = try client.result(&.{ "click", "--role", "button", "--name", "Save" });
    try client.expect(&.{ "text", "--selector", "#result" }, "Sample 🧭");
    _ = try client.result(&.{ "click", "--role", "slider", "--name", "Volume" });
    try client.expect(&.{ "eval", "trusted.every(Boolean)" }, true);
    const secret = "private fixture text\ntrailing newline\n";
    const filled = try client.run(&.{ "fill", "--role", "textbox", "--name", "Notes", "--value-file", "-" }, .{ .stdin = secret });
    try H.check(std.mem.indexOf(u8, try c.json(filled), "private fixture text") == null, "fill reply does not expose input");
    try client.expect(&.{ "eval", "document.querySelector('textarea').value" }, secret);
    const value_file = try c.path("value.txt");
    try c.write(value_file, "from-file");
    _ = try client.result(&.{ "fill", "--role", "textbox", "--name", "Editor", "--value-file", value_file });
    try client.expect(&.{ "text", "--role", "textbox", "--name", "Editor" }, "from-file");
    _ = try client.result(&.{ "press", "--role", "textbox", "--name", "Editor", "--key", "Control+a" });
    _ = try client.result(&.{ "press", "--key", "Backspace" });
    _ = try client.result(&.{ "press", "--key", "Shift+a" });
    try client.expect(&.{ "text", "--role", "textbox", "--name", "Editor" }, "A");
    _ = try client.result(&.{ "press", "--key", "Backspace" });
    try client.expect(&.{ "eval", "document.querySelector('[contenteditable]').textContent" }, "");
    _ = try client.result(&.{ "select", "--role", "combobox", "--name", "Choice", "--value", "b" });
    try client.expect(&.{ "eval", "document.querySelector('select').value" }, "b");
    _ = try client.failure(&.{ "select", "--selector", "select", "--value", "bad" }, "InvalidSelectOption");
    const duplicate = try H.field(try client.failure(&.{ "click", "--role", "button", "--name", "Duplicate" }, "AmbiguousLocator"), "error");
    try H.equal(try H.field(duplicate, "match_count"), 2);
    try H.equal(try H.field(duplicate, "action"), "not_started");
    _ = try client.failure(&.{ "click", "--role", "button", "--name", "Missing", "--timeout", "100" }, "ElementNotFound");
    _ = try client.failure(&.{ "click", "--role", "button", "--name", "Disabled", "--timeout", "100" }, "ElementDisabled");
    _ = try client.failure(&.{ "click", "--selector", "#covered", "--timeout", "100" }, "ElementCovered");
    _ = try client.result(&.{ "eval", "document.body.insertAdjacentHTML('beforeend', `<input id=readonly readonly><input id=invisible hidden><style>@keyframes motion {from{left:0px} to{left:500px}}</style><button id=moving style='position:fixed;top:300px;z-index:9999;animation:motion 1s linear infinite'>Moving</button>`); true" });
    _ = try client.failure(&.{ "fill", "--selector", "#readonly", "--value", "x" }, "ElementReadOnly");
    _ = try client.failure(&.{ "fill", "--selector", "#invisible", "--value", "x" }, "ElementNotVisible");
    const moving = try client.failure(&.{ "click", "--selector", "#moving", "--timeout", "350" }, "ElementNotStable");
    try H.equal(try H.field(try H.field(moving, "error"), "action"), "not_started");
    _ = try client.result(&.{ "eval", "document.querySelector('#moving').remove(); true" });
    _ = try client.result(&.{ "wait", "--selector", "#hidden", "--state", "hidden" });
    _ = try client.result(&.{ "wait", "--selector", "#missing", "--state", "detached" });
    _ = try client.result(&.{ "wait", "--selector", "#name", "--state", "visible" });
    _ = try client.result(&.{ "wait", "--selector", "#hidden", "--state", "attached" });
    const script = try c.path("inspect.js");
    try c.write(script, "({answer: 42})");
    try client.expect(&.{ "eval", "--script", script }, .{ .answer = 42 });
    try H.equal(try H.field(try client.run(&.{ "eval", "--script", "-" }, .{ .stdin = "6 * 7" }), "result"), 42);
    const result_file = try c.path("read.json");
    _ = try client.run(&.{ "read", "--limit", "17", "--out", result_file }, .{});
    const saved = try H.field(try c.parse(try c.read(result_file)), "result");
    try H.check((try H.field(saved, "truncated")).bool and (try H.field(saved, "returned_bytes")).integer <= 17, "bounded read file");
    try H.S.files.expectMode(c.io, .{ .path = result_file, .mode = 0o600 });
    _ = try client.result(&.{ "upload", "--selector", "#file", value_file });
    try client.expect(&.{ "eval", "document.querySelector('#file').files[0].text()" }, "from-file");
    const destination = try c.path("agent.txt");
    _ = try client.result(&.{ "download", "--role", "button", "--name", "Export", destination });
    try c.bytes(destination, "agent-download");
    _ = try client.result(&.{ "content", "<div style=\"height:3000px\">Tall page 🧭</div>" });
    const document = try client.result(&.{ "eval", "({w:document.documentElement.scrollWidth,h:document.documentElement.scrollHeight})" });
    const window = try client.result(&.{ "eval", "({w:innerWidth,h:innerHeight})" });
    const viewport_path = try c.path("viewport.png");
    const full_path = try c.path("full.png");
    _ = try client.run(&.{ "screenshot", "--out", viewport_path, "--viewport" }, .{});
    _ = try client.run(&.{ "screenshot", "--out", full_path, "--full-page" }, .{});
    const viewport = try H.S.png.dimensions(try c.read(viewport_path));
    const full = try H.S.png.dimensions(try c.read(full_path));
    try H.equal(window, .{ .w = viewport.width, .h = viewport.height });
    try H.equal(document, .{ .w = full.width, .h = full.height });
    try H.check(full.height >= 3000, "full-page screenshot includes tall document");
}
