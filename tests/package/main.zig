const std = @import("std");
const J = @import("cdp").journey;
const Agent = @import("cdp").agent;

test "independent consumer launches and evaluates" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const browser = try J.Browser.start(arena.allocator(), std.testing.io);
    defer browser.stop();
    const page = try browser.page(&.{});
    defer page.close();
    try std.testing.expectEqual(@as(i64, 3), J.number(try page.eval("1 + 2")));
    _ = try page.eval("document.body.innerHTML='<button>Package action</button>'; true");
    var diagnostics: Agent.Diagnostics = .{};
    var command = try Agent.Page.init(arena.allocator(), std.testing.io, &page.socket, 5000, &diagnostics);
    defer command.deinit();
    const snapshot = try command.snapshot(20_000);
    try std.testing.expect(J.number(J.field(snapshot, "returned_nodes")) > 0);
    try command.click(.{ .role = "button", .name = "Package action" });
    try std.testing.expectEqual(.completed, diagnostics.action);
    _ = try command.protocol("Page.getLayoutMetrics", try J.parse(arena.allocator(), "{}"));
    try command.content("<div id=from style='width:50px;height:50px'>From</div><div id=to style='width:50px;height:50px'>To</div>");
    try command.drag(.{ .selector = "#from" }, .{ .selector = "#to" }, 0, 2);
    const first = try arena.allocator().print("{s}/first.txt", .{browser.profile});
    const second = try arena.allocator().print("{s}/second.txt", .{browser.profile});
    try std.Io.Dir.cwd().writeFile(std.testing.io, .{ .sub_path = first, .data = "first" });
    try std.Io.Dir.cwd().writeFile(std.testing.io, .{ .sub_path = second, .data = "second" });
    try command.content("<input type=file multiple hidden>");
    try command.uploadFiles(.{ .selector = "input" }, &.{ first, second });
    try std.testing.expectEqual(@as(i64, 2), J.number(try command.eval("document.querySelector('input').files.length")));
    var connection = try Agent.Connection.connect(arena.allocator(), std.testing.io, try arena.allocator().print("http://127.0.0.1:{d}", .{browser.client.port}));
    defer connection.disconnect();
    try std.testing.expect((try connection.tabs()).array.items.len > 0);
    var borrowed = try connection.page(page.target);
    borrowed.close();
    connection.disconnect();
    var tab_arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    const tab = try browser.newTabWithOptions(tab_arena.allocator(), page.context, &.{}, .{ .background = true });
    const target = try arena.allocator().dupe(u8, tab.target);
    try std.testing.expect((try browser.tabsWithAllocator(arena.allocator(), page.context)).len == 2);
    tab.detach();
    tab_arena.deinit();
    const attached = try browser.attachTabWithOptions(arena.allocator(), target, page.context, &.{}, .{ .background = true });
    attached.detach();
    try browser.closeTab(target);
    try std.testing.expectEqual(@as(i64, 42), J.number(try page.eval("42")));
}
